    /** 94*94 = 8836 项，每项 4 个 hex 字符 */
    private static final int[] TABLE = new int[8836];

    private static boolean sReady = false;

    private Gb2312Table() {
    }

    private static synchronized void ensure() {
        if (sReady) {
            return;
        }
        for (int i = 0; i < TABLE.length; i++) {
            int p = i * 4;
            TABLE[i] = (hex(p) << 12) | (hex(p + 1) << 8) | (hex(p + 2) << 4) | hex(p + 3);
        }
        sReady = true;
    }

    private static int hex(int index) {
        char c = HEX.charAt(index);
        if (c >= '0' && c <= '9') {
            return c - '0';
        }
        if (c >= 'A' && c <= 'F') {
            return c - 'A' + 10;
        }
        return c - 'a' + 10;
    }

    /**
     * 查表。
     *
     * @param row  区号 0x01 - 0x5E（对应字节高 7 位）
     * @param cell 位号 0x01 - 0x5E
     * @return Unicode 码点；0 或 0xFFFF 表示无对应字符
     */
    public static int lookup(int row, int cell) {
        if (row < 1 || row > 94 || cell < 1 || cell > 94) {
            return 0;
        }
        ensure();
        return TABLE[(row - 1) * 94 + (cell - 1)];
    }

    public static boolean isDefined(int code) {
        return code != 0 && code != 0xFFFF;
    }
